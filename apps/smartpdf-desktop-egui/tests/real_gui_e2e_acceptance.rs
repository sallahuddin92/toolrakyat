fn resolve_path(rel: &str) -> PathBuf {
    let p1 = PathBuf::from(rel);
    if p1.exists() {
        return p1;
    }
    let p2 = PathBuf::from("../../").join(rel);
    if p2.exists() {
        return p2;
    }
    p1
}

/// Helper to simulate a full egui rendering frame through the application
fn step_app_frame(app: &mut SmartPdfEguiApp, ctx: &egui::Context) {
    let raw_input = egui::RawInput::default();
    let mut output = ctx.run_ui(raw_input, |ui| {
        app.render_frame(ui);
    });
    output.textures_delta.clear();
}

#[test]
fn test_01_real_gui_empty_workspace_and_single_document_open() {
    let ctx = egui::Context::default();
    ctx.set_fonts(theme::font_definitions());

    let mut app = SmartPdfEguiApp::new_headless();

    // 1. Initial State: No document open
    step_app_frame(&mut app, &ctx);
    assert!(app.manager.active_session().is_none());
    assert!(app.page_texture.is_none());
    assert!(app.last_rendered_key.is_none());

    // 2. Open Document 1 via application method
    let heading_path = resolve_path(HEADING_PDF_PATH);
    assert!(heading_path.exists(), "Sample heading PDF must exist");
    app.open_file_path(&heading_path).expect("open heading pdf");

    // 3. Render GUI frame after opening
    step_app_frame(&mut app, &ctx);

    // Verify session state
    assert_eq!(app.manager.session_count(), 1);
    let session = app.manager.active_session().expect("active session");
    assert_eq!(session.title, "text-multispan-heading.pdf");
    assert_eq!(session.total_pages, 1);
    assert_eq!(session.current_page, 0);

    // Verify texture generation & session-aware rendering key
    assert!(
        app.page_texture.is_some(),
        "Page texture must be generated by egui frame"
    );
    assert!(app.last_rendered_key.is_some());
    let (key_session_id, rev, page, _, _) = app.last_rendered_key.as_ref().unwrap();
    assert_eq!(key_session_id, &session.id);
    assert_eq!(*rev, 0);
    assert_eq!(*page, 0);
    println!(
        "  [GUI E2E PASS]: Document 1 opened, texture loaded (session={})",
        key_session_id
    );
}

#[test]
fn test_02_real_gui_multi_document_tabs_and_session_switching() {
    let ctx = egui::Context::default();
    ctx.set_fonts(theme::font_definitions());

    let mut app = SmartPdfEguiApp::new_headless();

    // 1. Open Document 1
    app.open_file_path(resolve_path(HEADING_PDF_PATH))
        .expect("open doc 1");
    step_app_frame(&mut app, &ctx);

    let doc1_id = app.manager.active_session().unwrap().id.clone();
    let doc1_tex_id = app.page_texture.as_ref().unwrap().id();

    // 2. Open Document 2 in separate tab
    let invoice_path = resolve_path(INVOICE_PDF_PATH);
    if !invoice_path.exists() {
        println!("Skipping multi-document test: invoice path not found");
        return;
    }
    app.open_file_path(&invoice_path).expect("open doc 2");
    step_app_frame(&mut app, &ctx);

    assert_eq!(app.manager.session_count(), 2);
    assert_eq!(app.manager.tabs().len(), 2);

    let doc2_id = app.manager.active_session().unwrap().id.clone();
    assert_ne!(doc1_id, doc2_id);

    // Verify texture updated to Document 2
    let doc2_tex_id = app.page_texture.as_ref().unwrap().id();
    assert_ne!(
        doc1_tex_id, doc2_tex_id,
        "Texture must update when opening Document 2"
    );
    assert_eq!(app.last_rendered_key.as_ref().unwrap().0, doc2_id);

    // 3. Switch back to Document 1
    app.manager
        .dispatch(AppCommand::SwitchTab {
            session_id: doc1_id.clone(),
        })
        .unwrap();
    app.invalidate_render();
    step_app_frame(&mut app, &ctx);

    assert_eq!(app.manager.active_session().unwrap().id, doc1_id);
    assert_eq!(
        app.last_rendered_key.as_ref().unwrap().0,
        doc1_id,
        "Render key must match Document 1"
    );

    // 4. Close Document 1
    app.manager
        .dispatch(AppCommand::CloseSession {
            session_id: doc1_id,
        })
        .unwrap();
    app.invalidate_render();
    step_app_frame(&mut app, &ctx);

    assert_eq!(app.manager.session_count(), 1);
    assert_eq!(app.manager.active_session().unwrap().id, doc2_id);
    assert_eq!(app.last_rendered_key.as_ref().unwrap().0, doc2_id);
    println!("  [GUI E2E PASS]: Multi-document tabs, switching, and closing verified");
}

#[test]
fn test_03_real_gui_zoom_mutation_save_reopen_and_oracle_validation() {
    let ctx = egui::Context::default();
    ctx.set_fonts(theme::font_definitions());

    let mut app = SmartPdfEguiApp::new_headless();
    app.open_file_path(resolve_path(HEADING_PDF_PATH))
        .expect("open heading");
    step_app_frame(&mut app, &ctx);

    let session_id = app.manager.active_session().unwrap().id.clone();

    // 1. Zoom adjustment
    app.zoom_percent = 150.0;
    step_app_frame(&mut app, &ctx);
    assert_eq!(
        app.last_rendered_key.as_ref().unwrap().3,
        150.0_f32.to_bits()
    );

    // 2. Interactive mutation: Add highlight annotation
    let mut_res = app
        .manager
        .dispatch(AppCommand::AddAnnotation {
            page_index: 0,
            subtype: "Highlight".into(),
            rect: [50.0, 700.0, 250.0, 720.0],
            contents: Some("E2E GUI Highlight".into()),
            color: Some(vec![1.0, 0.85, 0.0]),
        })
        .expect("add annotation");
    assert!(mut_res.success);
    assert!(app.manager.active_session().unwrap().is_dirty());

    // Re-render frame
    app.invalidate_render();
    step_app_frame(&mut app, &ctx);
    assert_eq!(
        app.last_rendered_key.as_ref().unwrap().1,
        1,
        "Revision must be incremented to 1"
    );

    // 3. Save As to temporary disk location
    let temp_save_path =
        std::env::temp_dir().join(format!("smartpdf_gui_e2e_{}.pdf", std::process::id()));
    let saved_path = app
        .save_active_document(Some(temp_save_path.clone()))
        .expect("save active document");
    assert_eq!(saved_path, temp_save_path);
    assert!(temp_save_path.exists());
    let file_size = std::fs::metadata(&temp_save_path).unwrap().len();
    assert!(file_size > 0, "Saved PDF must have non-zero size");

    // 4. Close session and verify empty state
    app.manager
        .dispatch(AppCommand::CloseSession { session_id })
        .unwrap();
    app.invalidate_render();
    step_app_frame(&mut app, &ctx);
    assert!(app.manager.active_session().is_none());
    assert!(app.page_texture.is_none());

    // 5. Reopen saved file from disk through GUI method
    app.open_file_path(&temp_save_path)
        .expect("reopen saved PDF");
    step_app_frame(&mut app, &ctx);
    assert_eq!(app.manager.session_count(), 1);
    assert!(app.page_texture.is_some());

    // 6. Independent Oracle Validation (PyMuPDF & PDFium)
    let oracle_script = format!(
        r#"
import fitz
import pypdfium2 as pdfium

doc_path = "{}"
# 1. PyMuPDF Check
doc = fitz.open(doc_path)
assert len(doc) == 1, "Expected 1 page in saved PDF"
page = doc[0]
annots = list(page.annots())
assert len(annots) >= 1, "Expected at least 1 annotation in saved PDF"
print(f"PyMuPDF validated: {{len(annots)}} annotations found")

# 2. PDFium Check
p_doc = pdfium.PdfDocument(doc_path)
assert len(p_doc) == 1, "PDFium expected 1 page"
p_page = p_doc[0]
image = p_page.render(scale=1.0).to_pil()
assert image.width > 0 and image.height > 0
print(f"PDFium validated: rendered successfully at {{image.width}}x{{image.height}}")
"#,
        temp_save_path.display()
    );

    let output = std::process::Command::new("python3")
        .args(["-c", &oracle_script])
        .output();

    if let Ok(out) = output {
        let stdout = String::from_utf8_lossy(&out.stdout);
        let stderr = String::from_utf8_lossy(&out.stderr);
        println!("Oracle validation stdout:\n{}", stdout);
        if !out.status.success() {
            panic!("Oracle validation failed: {}", stderr);
        }
    } else {
        println!("Warning: python3 not available for oracle validation");
    }

    // Clean up temp file
    let _ = std::fs::remove_file(&temp_save_path);
    println!("  [GUI E2E PASS]: Zoom, mutation, atomic save, disk reopen, and dual oracle verification succeeded");
}

